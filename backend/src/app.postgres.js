import express from "express";
import cookieParser from "cookie-parser";
import cors from "cors";
import userRoutes from "./routes/user.route.postgres.js";
import categoryRoutes from "./routes/category.route.postgres.js";
import productRoutes from "./routes/product.route.postgres.js";
import orderRoutes from "./routes/order.route.postgres.js";
import { errorMiddleware } from "./middlewares/error.middleware.js";

export const app = express();
app.use(cors({ origin: process.env.CORS_ORIGIN, credentials: true }));
app.use(express.json({ limit: "16kb" }));
app.use(express.urlencoded({ extended: true, limit: "16kb" }));
app.use(express.static("public"));
app.use(cookieParser());
app.use("/api/v1/users", userRoutes);
app.use("/api/v1/categories", categoryRoutes);
app.use("/api/v1/products", productRoutes);
app.use("/api/v1/orders", orderRoutes);
app.use(errorMiddleware);
